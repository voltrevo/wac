#!/usr/bin/env python3
"""Reference values for core/test/math_test.wac — `python3 core/test/genmath.py > core/test/mathvectors.wac`.

Each function's inputs come from a 64-bit xorshift that math_test.wac runs too, so only the answers are
written down: the true value worked out with `decimal` at 400 digits — enough that `1 + x` keeps all of a
tiny `x`, which 120 did not — and rounded once to the nearest double (Python's float() of a decimal string
rounds correctly). A function within one ulp answers either that
double or a neighbour; the test says how many are exactly it.
"""
import struct
from decimal import Decimal, getcontext

getcontext().prec = 400
M64 = (1 << 64) - 1
N = 1000


def f2b(x):
    return struct.unpack('<Q', struct.pack('<d', x))[0]


def b2f(b):
    return struct.unpack('<d', struct.pack('<Q', b))[0]


class Rng:
    def __init__(self, seed):
        self.s = seed

    def next(self):
        x = self.s
        x ^= (x << 13) & M64
        x ^= x >> 7
        x ^= (x << 17) & M64
        self.s = x
        return x

    def unit(self):
        """A double in [0, 1), from the top 53 bits."""
        return float(self.next() >> 11) / 9007199254740992.0


def positive(r, i):
    """A positive finite double: every 4th in [0.5, 2), the rest across every exponent, subnormals included."""
    if i % 4 == 0:
        return b2f(0x3FE0000000000000 + r.next() % (1 << 53))
    e = r.next() % 2046
    m = r.next() & ((1 << 52) - 1)
    return b2f((e << 52) | m)


def small(r):
    """A double of magnitude below 2^-1 and above about 2^-123, of either sign."""
    e = 900 + r.next() % 122
    m = r.next() & ((1 << 52) - 1)
    sign = (r.next() & 1) << 63
    return b2f(sign | (e << 52) | m)


def inputs(name):
    seeds = {'log': 1, 'log2': 2, 'log10': 3, 'log1p': 4, 'exp': 5, 'expm1': 6, 'pow': 7}
    r = Rng(0x9E3779B97F4A7C15 ^ seeds[name])
    out = []
    for i in range(N):
        if name in ('log', 'log2', 'log10'):
            out.append((positive(r, i),))
        elif name == 'log1p':
            if i % 3 == 0:
                out.append((small(r),))
            elif i % 3 == 1:
                out.append((r.unit() * 1.99 - 0.99,))
            else:
                out.append((positive(r, i),))
        elif name == 'exp':
            out.append((small(r),) if i % 4 == 0 else (-745.0 + r.unit() * 1454.7,))
        elif name == 'expm1':
            out.append((small(r),) if i % 4 == 0 else (-40.0 + r.unit() * 749.7,))
        elif name == 'pow':
            e = 1003 + r.next() % 41
            x = b2f((e << 52) | (r.next() & ((1 << 52) - 1)))
            if i % 5 == 0:
                y = float(r.next() % 41) - 20.0
                x = -x
            else:
                y = -50.0 + r.unit() * 100.0
            out.append((x, y))
    return out


def ln(d):
    return d.ln()


def expected(name, args):
    x = Decimal(args[0])
    if name == 'log':
        v = ln(x)
    elif name == 'log2':
        v = ln(x) / ln(Decimal(2))
    elif name == 'log10':
        v = x.log10()
    elif name == 'log1p':
        v = ln(1 + x)
    elif name == 'exp':
        v = x.exp()
    elif name == 'expm1':
        v = x.exp() - 1
    elif name == 'pow':
        y = Decimal(args[1])
        sign = 1
        if x < 0:
            sign = -1 if int(y) % 2 == 1 else 1
            x = -x
        v = sign * (y * ln(x)).exp()
    return float(str(v))


def main():
    print('// Generated by `python3 core/test/genmath.py > core/test/mathvectors.wac`. Do not edit.')
    print('//')
    print("// The correctly rounded answer for each of a function's inputs, as 16 hex digits each — the inputs are")
    print("// math_test.wac's own xorshift sequence, so they are not written down.")
    print()
    for name in ('log', 'log2', 'log10', 'log1p', 'exp', 'expm1', 'pow'):
        hexes = ''.join('%016x' % f2b(expected(name, a)) for a in inputs(name))
        print('export string %sExpected() {' % name)
        print('  return "%s";' % hexes)
        print('}')
        print()


main()
